#!/usr/bin/env bash
# Regenerates everything derived from /etc/mailserver and /etc/dovecot/users, then reloads services:
#   Postfix tables, Rspamd's DKIM selector map, the Sieve rule that files reports, the MTA-STS policy
#   and the Thunderbird autoconfig files.
# Usage: mailctl apply [--no-reload]
source "$(dirname "$0")/../lib/common.sh"
require_root
load_config
take_lock

reload=1
[[ ${1:-} == "--no-reload" ]] && reload=0

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

mapfile -t domains < <(list_domains)
mapfile -t mailboxes < <(list_mailboxes)
header="# Generated by 'mailctl apply' from /etc/mailserver. Do not edit."

# ---- Postfix: hosted domains
{
  echo "$header"
  for d in "${domains[@]}"; do echo "$d OK"; done
} >"$tmp/vmail_domains"

# ---- Postfix: mailboxes, and who may send from which address
{
  echo "$header"
  for m in "${mailboxes[@]}"; do
    domain_exists "${m#*@}" || warn "mailbox $m belongs to a domain that is not hosted"
    echo "$m OK"
  done
} >"$tmp/vmail_mailboxes"

{ echo "$header"; for m in "${mailboxes[@]}"; do echo "$m $m"; done; } >"$tmp/sender_login"
echo "$header" >"$tmp/virtual_aliases"

while read -r alias targets; do
  [[ -n $alias ]] || continue
  domain_exists "${alias#*@}" || warn "alias $alias belongs to a domain that is not hosted"
  echo "$alias $targets" >>"$tmp/virtual_aliases"
  owners=()
  IFS=',' read -ra target_list <<<"$targets"
  for t in "${target_list[@]}"; do
    if mailbox_exists "$t"; then owners+=("$t"); fi
  done
  if ((${#owners[@]})); then
    (IFS=','; echo "$alias ${owners[*]}") >>"$tmp/sender_login"
  fi
done < <(list_aliases)

for f in vmail_domains vmail_mailboxes virtual_aliases sender_login; do
  install_file "$tmp/$f" "/etc/postfix/$f"
done

# ---- Rspamd: DKIM selector per domain (only domains that have a key)
{
  for d in "${domains[@]}"; do
    sel=$(domain_selector "$d")
    if [[ -r $(dkim_key_file "$d" "$sel") ]]; then echo "$d $sel"; else warn "no DKIM key for $d"; fi
  done
} >"$tmp/dkim_selectors.map"
install_file "$tmp/dkim_selectors.map" "$DKIM_SELECTOR_MAP"

# ---- Sieve: mail to reports@ of a hosted domain (DMARC and TLS reports) is filed into Reports
report_addresses='"reports@invalid"'   # a Sieve list needs at least one entry
if ((${#domains[@]})); then
  report_addresses=$(printf '"reports@%s", ' "${domains[@]}")
  report_addresses=${report_addresses%, }
fi
# shellcheck disable=SC2016  # the ${...} is for envsubst, not the shell
REPORT_ADDRESSES=$report_addresses envsubst '${REPORT_ADDRESSES}' \
  <"$TEMPLATE_DIR/dovecot/sieve/before.sieve" >"$tmp/before.sieve"
if ! cmp -s "$tmp/before.sieve" /etc/dovecot/sieve/before.sieve; then
  install_file "$tmp/before.sieve" /etc/dovecot/sieve/before.sieve
  sievec /etc/dovecot/sieve/before.sieve
fi

# ---- MTA-STS policy (same for every domain; served at https://mta-sts.<domain>/.well-known/mta-sts.txt)
printf 'version: STSv1\r\nmode: %s\r\nmx: %s\r\nmax_age: %s\r\n' \
  "$MTA_STS_MODE" "$MAIL_HOSTNAME" 604800 >"$tmp/mta-sts.txt"
install_file "$tmp/mta-sts.txt" "$WEB_ROOT/.well-known/mta-sts.txt"

# ---- Thunderbird autoconfig, one file per domain (served at https://autoconfig.<domain>/mail/config-v1.1.xml)
# Each file names only its own domain, so asking about one domain doesn't reveal the others.
autoconfig_dir="$WEB_ROOT/autoconfig"
install -d -m 0755 "$autoconfig_dir"
for d in "${domains[@]}"; do
  cat >"$tmp/autoconfig.$d.xml" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<clientConfig version="1.1">
  <emailProvider id="$d">
    <domain>$d</domain>
    <displayName>%EMAILDOMAIN% mail</displayName>
    <displayShortName>%EMAILDOMAIN%</displayShortName>
    <incomingServer type="imap">
      <hostname>$MAIL_HOSTNAME</hostname>
      <port>993</port>
      <socketType>SSL</socketType>
      <authentication>password-cleartext</authentication>
      <username>%EMAILADDRESS%</username>
    </incomingServer>
    <outgoingServer type="smtp">
      <hostname>$MAIL_HOSTNAME</hostname>
      <port>465</port>
      <socketType>SSL</socketType>
      <authentication>password-cleartext</authentication>
      <username>%EMAILADDRESS%</username>
    </outgoingServer>
  </emailProvider>
</clientConfig>
EOF
  install_file "$tmp/autoconfig.$d.xml" "$autoconfig_dir/autoconfig.$d.xml"
done
# Files of domains that are no longer hosted
for f in "$autoconfig_dir"/autoconfig.*.xml; do
  [[ -e $f && ! -e $tmp/$(basename "$f") ]] || continue
  rm -f "$f"
  printf '    removed %s\n' "$f"
done

# ---- Reload
if ((reload)); then
  postfix check
  if postfix status >/dev/null 2>&1; then postfix reload >/dev/null 2>&1; fi
  reload_if_active rspamd
  info "applied: ${#domains[@]} domain(s), ${#mailboxes[@]} mailbox(es), $(list_aliases | wc -l) alias(es)"
fi
