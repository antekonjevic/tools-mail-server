-- Logged-in users may put only their own addresses in the From header.
-- Postfix already checks the envelope sender (MAIL FROM) against /etc/postfix/sender_login
-- (reject_sender_login_mismatch). This applies the same table to the From header, which is what
-- recipients see and what the DKIM signature vouches for. Mail that fails is rejected, so the
-- mail app shows an error instead of the message going out.
-- Managed by the mailserver scripts: edit templates/rspamd/rspamd.local.lua and re-run
-- scripts/10-install-mail.sh.

local rspamd_logger = require "rspamd_logger"

-- "address login[,login...]" per line, generated by "mailctl apply"
local owners = rspamd_config:add_map({
  type = 'map',
  url = '/etc/postfix/sender_login',
  description = 'logins that may send as each address',
})

local function owned_by(address, user)
  -- me+anything@example.com belongs to whoever owns me@example.com
  local base = address:gsub('%+[^@]*@', '@', 1)
  local logins = owners and owners:get_key(base)
  if not logins then return false end
  for login in tostring(logins):gmatch('[^,%s]+') do
    if login:lower() == user then return true end
  end
  return false
end

local function reject(task, message)
  rspamd_logger.infox(task, 'rejected: %s', message)
  task:set_pre_result('reject', message, 'mailserver_from_check')
end

rspamd_config:register_symbol({
  name = 'MAILSERVER_FROM_NOT_OWNED',
  type = 'prefilter',
  flags = 'empty',
  callback = function(task)
    local user = task:get_user()
    if not user then return end -- only mail sent by logged-in users is checked
    user = user:lower()
    local from = task:get_from('mime') or {}
    if #from == 0 then
      return reject(task, 'The message has no From address')
    end
    for _, a in ipairs(from) do
      local address = (a.addr or ''):lower()
      if not owned_by(address, user) then
        return reject(task, string.format('%s may not send as <%s>', user, address))
      end
    end
  end,
})
